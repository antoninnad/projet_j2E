-- Chat privé entre deux membres actifs d'une même entreprise (T33).
-- participant_a_id < participant_b_id : une seule conversation par paire.

CREATE TABLE IF NOT EXISTS conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    participant_a_id BIGINT NOT NULL,
    participant_b_id BIGINT NOT NULL,
    participant_a_last_read_id BIGINT,
    participant_b_last_read_id BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_activity_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_conversation_participants UNIQUE (participant_a_id, participant_b_id),
    CONSTRAINT ck_conversation_participants_order CHECK (participant_a_id < participant_b_id),
    CONSTRAINT fk_conversations_company FOREIGN KEY (company_id) REFERENCES companies(id),
    CONSTRAINT fk_conversations_participant_a FOREIGN KEY (participant_a_id) REFERENCES users(id),
    CONSTRAINT fk_conversations_participant_b FOREIGN KEY (participant_b_id) REFERENCES users(id)
);

CREATE INDEX IF NOT EXISTS idx_conversations_a_activity ON conversations (participant_a_id, last_activity_at);
CREATE INDEX IF NOT EXISTS idx_conversations_b_activity ON conversations (participant_b_id, last_activity_at);

CREATE TABLE IF NOT EXISTS chat_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL,
    sender_id BIGINT NOT NULL,
    content VARCHAR(4000) NOT NULL,
    client_message_id VARCHAR(64),
    sent_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_chat_message_client_id UNIQUE (conversation_id, sender_id, client_message_id),
    CONSTRAINT fk_chat_messages_conversation FOREIGN KEY (conversation_id) REFERENCES conversations(id),
    CONSTRAINT fk_chat_messages_sender FOREIGN KEY (sender_id) REFERENCES users(id)
);

CREATE INDEX IF NOT EXISTS idx_chat_messages_conversation_id ON chat_messages (conversation_id, id);
