CREATE TABLE IF NOT EXISTS companies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    code VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS admins (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    first_name VARCHAR(255) NOT NULL,
    last_name VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    status VARCHAR(32) NOT NULL,
    role VARCHAR(32) NOT NULL,
    company_id BIGINT NOT NULL,
    CONSTRAINT fk_users_company FOREIGN KEY (company_id) REFERENCES companies(id)
);

CREATE TABLE IF NOT EXISTS user_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bio VARCHAR(255),
    profile_picture_url VARCHAR(255),
    user_id BIGINT NOT NULL UNIQUE,
    CONSTRAINT fk_profiles_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS departments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    company_id BIGINT NOT NULL,
    CONSTRAINT uk_department_company_name UNIQUE (company_id, name),
    CONSTRAINT fk_departments_company FOREIGN KEY (company_id) REFERENCES companies(id)
);

CREATE TABLE IF NOT EXISTS memberships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    access_level INTEGER NOT NULL,
    user_id BIGINT NOT NULL,
    department_id BIGINT NOT NULL,
    CONSTRAINT uk_membership_user_department UNIQUE (user_id, department_id),
    CONSTRAINT fk_memberships_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_memberships_department FOREIGN KEY (department_id) REFERENCES departments(id)
);

CREATE TABLE IF NOT EXISTS nodes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE,
    version BIGINT NOT NULL,
    parent_id BIGINT,
    company_id BIGINT NOT NULL,
    department_id BIGINT NOT NULL,
    owner_id BIGINT NOT NULL,
    min_access_level INTEGER NOT NULL,
    CONSTRAINT fk_nodes_company FOREIGN KEY (company_id) REFERENCES companies(id),
    CONSTRAINT fk_nodes_department FOREIGN KEY (department_id) REFERENCES departments(id),
    CONSTRAINT fk_nodes_owner FOREIGN KEY (owner_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS folders (
    id BIGINT NOT NULL PRIMARY KEY,
    CONSTRAINT fk_folders_node FOREIGN KEY (id) REFERENCES nodes(id)
);

CREATE TABLE IF NOT EXISTS files (
    id BIGINT NOT NULL PRIMARY KEY,
    original_file_name VARCHAR(255) NOT NULL,
    content_type VARCHAR(255),
    size BIGINT NOT NULL,
    storage_path VARCHAR(255) NOT NULL,
    CONSTRAINT fk_files_node FOREIGN KEY (id) REFERENCES nodes(id)
);

CREATE TABLE IF NOT EXISTS node_contributors (
    node_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    PRIMARY KEY (node_id, user_id),
    CONSTRAINT fk_contributors_node FOREIGN KEY (node_id) REFERENCES nodes(id),
    CONSTRAINT fk_contributors_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action VARCHAR(255) NOT NULL,
    timestamp VARCHAR(255) NOT NULL,
    admin_id BIGINT NOT NULL,
    CONSTRAINT fk_logs_admin FOREIGN KEY (admin_id) REFERENCES admins(id)
);
