-- Favoris personnels (T31). Un favori ne donne aucun droit : il est filtré à la lecture selon l'accès actuel.
-- Il disparaît avec l'élément ou le compte (ON DELETE CASCADE).

CREATE TABLE IF NOT EXISTS favorites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    node_id BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_favorite_user_node UNIQUE (user_id, node_id),
    CONSTRAINT fk_favorites_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_favorites_node FOREIGN KEY (node_id) REFERENCES nodes(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_favorites_user_created ON favorites (user_id, created_at);
